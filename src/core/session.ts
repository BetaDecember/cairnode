import fs from 'node:fs/promises'
import path from 'node:path'
import { randomUUID } from 'node:crypto'
import type { SessionMeta } from './types.ts'
import type { ChatMessage } from './provider/types.ts'

/**
 * Append-only JSONL session storage.
 *
 * The format mirrors the agent loop's requirements: history is only ever
 * appended, so replaying a session reconstructs exactly the message list the
 * model saw. Rewriting history would invalidate the KV cache on the next turn.
 *
 *   {"type":"meta","id":"…","cwd":"…","createdAt":"…"}
 *   {"type":"message","at":"…","message":{…}}
 */

interface MetaLine {
  type: 'meta'
  id: string
  cwd: string
  createdAt: string
}

interface MessageLine {
  type: 'message'
  at: string
  message: ChatMessage
}

export interface SessionRecord {
  meta: SessionMeta
  messages: ChatMessage[]
}

const ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/

/** Session ids are generated by this module, but never trust a path from IPC. */
function assertId(id: string): void {
  if (!ID_PATTERN.test(id)) throw new Error(`Invalid session id: ${id}`)
}

/** One-line text for the sidebar: no markdown markers, no runs of whitespace. */
function cleanLine(text: string): string {
  return text
    .replace(/`/g, '')
    .replace(/\*\*/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

export function titleFromText(text: string): string {
  const clean = cleanLine(text)
  if (!clean) return 'New session'
  return clean.length > 64 ? `${clean.slice(0, 61)}…` : clean
}

/**
 * Drop an assistant turn whose tool calls were never answered, and any tool
 * message with no call to answer.
 *
 * This is what a crash mid-turn leaves behind. Sending it back to the model
 * would be rejected, so a session must stay loadable after an unclean exit.
 */
export function repairConversation(messages: ChatMessage[]): ChatMessage[] {
  const out: ChatMessage[] = []
  let pending = 0
  let groupStart = -1

  for (const message of messages) {
    if (message.role === 'tool') {
      if (pending <= 0) continue
      out.push(message)
      pending--
      continue
    }

    if (pending > 0) {
      // Incomplete group: remove the assistant turn and its partial results.
      out.length = groupStart
      pending = 0
    }

    if (message.role === 'assistant' && message.toolCalls?.length) {
      groupStart = out.length
      pending = message.toolCalls.length
    }
    out.push(message)
  }

  if (pending > 0 && groupStart >= 0) out.length = groupStart
  return out
}

function previewFromMessages(messages: ChatMessage[]): string {
  for (let index = messages.length - 1; index >= 0; index--) {
    const message = messages[index]
    if (message?.role !== 'assistant') continue
    const firstLine = message.content.split('\n').find((line) => line.trim())
    if (!firstLine) continue
    const clean = cleanLine(firstLine)
    return clean.length > 96 ? `${clean.slice(0, 93)}…` : clean
  }
  return messages.length === 0 ? 'No messages yet' : `${messages.length} messages`
}

function deriveMeta(
  base: Omit<MetaLine, 'type'>,
  messages: ChatMessage[],
  at: string | null,
): SessionMeta {
  const firstUser = messages.find((message) => message.role === 'user')
  return {
    id: base.id,
    cwd: base.cwd,
    createdAt: base.createdAt,
    updatedAt: at ?? base.createdAt,
    title: firstUser ? titleFromText(firstUser.content) : 'New session',
    preview: previewFromMessages(messages),
    messageCount: messages.length,
  }
}

export class SessionStore {
  private readonly root: string

  constructor(root: string) {
    this.root = root
  }

  private filePath(id: string): string {
    assertId(id)
    return path.join(this.root, `${id}.jsonl`)
  }

  async create(cwd: string, title?: string): Promise<SessionMeta> {
    const id = randomUUID()
    const createdAt = new Date().toISOString()
    const meta: MetaLine = { type: 'meta', id, cwd, createdAt }

    await fs.mkdir(this.root, { recursive: true })
    await fs.writeFile(this.filePath(id), `${JSON.stringify(meta)}\n`, 'utf8')

    const messages: ChatMessage[] = title
      ? [{ role: 'user', content: title }]
      : []
    if (title) await this.append(id, messages)

    return deriveMeta({ id, cwd, createdAt }, messages, null)
  }

  async append(id: string, messages: ChatMessage[]): Promise<void> {
    if (messages.length === 0) return
    const at = new Date().toISOString()
    const body = messages
      .map((message) => JSON.stringify({ type: 'message', at, message } satisfies MessageLine))
      .join('\n')
    await fs.mkdir(this.root, { recursive: true })
    await fs.appendFile(this.filePath(id), `${body}\n`, 'utf8')
  }

  async load(id: string): Promise<SessionRecord | null> {
    // Validate before the try: an invalid id is a caller error, not a miss.
    const file = this.filePath(id)

    let raw: string
    try {
      raw = await fs.readFile(file, 'utf8')
    } catch {
      return null
    }

    let base: MetaLine | null = null
    const messages: ChatMessage[] = []
    let lastAt: string | null = null

    for (const line of raw.split('\n')) {
      if (!line.trim()) continue
      try {
        const parsed = JSON.parse(line) as MetaLine | MessageLine
        if (parsed.type === 'meta') base = parsed
        else if (parsed.type === 'message' && parsed.message) {
          messages.push(parsed.message)
          lastAt = parsed.at ?? lastAt
        }
      } catch {
        // A truncated final line is expected if the process died mid-write.
        // Skipping it keeps the rest of the session usable.
      }
    }

    if (!base) return null
    const repaired = repairConversation(messages)
    return {
      meta: deriveMeta(
        { id: base.id, cwd: base.cwd, createdAt: base.createdAt },
        repaired,
        lastAt,
      ),
      messages: repaired,
    }
  }

  async list(): Promise<SessionMeta[]> {
    let entries: string[]
    try {
      entries = await fs.readdir(this.root)
    } catch {
      return []
    }

    const sessions: SessionMeta[] = []
    for (const entry of entries) {
      if (!entry.endsWith('.jsonl')) continue
      const record = await this.load(entry.slice(0, -'.jsonl'.length))
      if (record) sessions.push(record.meta)
    }

    sessions.sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))
    return sessions
  }

  async remove(id: string): Promise<void> {
    await fs.rm(this.filePath(id), { force: true })
  }
}
